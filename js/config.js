function normalizePessoaKey(value) {
    return String(value || "")
        .normalize("NFD")
        .replace(/[\u0300-\u036f]/g, "")
        .toLowerCase()
        .replace(/[^a-z0-9]+/g, "-")
        .replace(/^-+|-+$/g, "");
}

export function getFuncionarioKeyFromFields(nome, cpf) {
    const cpfLimpo = String(cpf || "").trim();
    return cpfLimpo ? `cpf:${cpfLimpo}` : `nome:${normalizePessoaKey(nome)}`;
}

